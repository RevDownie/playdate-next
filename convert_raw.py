import subprocess
import argparse
import os
import shutil
import drop_sprites
import character_sprites
import gore_sprites
import env_kits
import convert_tilemaps

"""
Simple script for running Imagemagick on source images to convert them to 1 bit images for Playdate
"""
CHAR_W = character_sprites.HERO_W  # The player's cell: gameplay sizes (collision radii, melee range) derive from it
CHAR_H = character_sprites.HERO_H

"""
Write a zig file with the dimensions
"""
def createDescFile():
    with open("src/bitmap_descs.zig", 'w') as f:
        f.write("//Autogenerated\n")
        f.write(f"pub const CHAR_W: u32 = {CHAR_W};\n")
        f.write(f"pub const CHAR_H: u32 = {CHAR_H};\n")
        f.write(f"pub const DROP_W: u32 = {drop_sprites.DROP_W};\n")
        f.write(f"pub const DROP_H: u32 = {drop_sprites.DROP_H};\n")
        f.write(f"pub const DROP_FRAMES_PER_KIND: u32 = {drop_sprites.FRAMES_PER_KIND};\n")
        for line in character_sprites.desc_lines() + gore_sprites.desc_lines():
            f.write(line + "\n")
        f.close();


if __name__ == "__main__":
    parser = argparse.ArgumentParser(prog = 'Convert Raw Images', description = 'Convert pngs to 1bit images for Playdate')
    parser.add_argument('imagemagick') 

    args = parser.parse_args() 

    if os.path.isdir('images'):
        shutil.rmtree('images')
    os.mkdir('images')

    # Characters (modelled and rendered to 1-bit, written directly)
    character_sprites.save(character_sprites.build(), 'images')
    gore_sprites.save(gore_sprites.build(), 'images')

    # Environment kits (modelled and dithered, written directly, plus src/kit_descs.zig and the Tiled tilesets),
    # then the levels and their baked ground
    kits = env_kits.write('images')
    convert_tilemaps.convert_all('images', kits)

    # Drops (hand authored 1-bit, written directly)
    drop_sprites.write('images')

    # Launchers
    cmds = [args.imagemagick, "raw-images\\card.png", "-colorspace", "gray", "images\\card.png"]
    p = subprocess.Popen(cmds, stdout=subprocess.PIPE, shell=True)
    p.communicate()

    createDescFile()
