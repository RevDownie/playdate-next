// Platform layer: owns all memory and state, talks to the Playdate API, and each frame turns its input into
// a `state.Input`, ticks the game and renders it. Control flows one way: main -> game -> systems.

/// Memory. Everything is carved from one static buffer up front; nothing is allocated from the heap.
/// app (whole run) -> level (reset when a level loads) and frame (reset at the start of every frame)
const LEVEL_ARENA_SIZE = 64 * 1024;
const FRAME_ARENA_SIZE = 64 * 1024;
const APP_MEMORY_SIZE = LEVEL_ARENA_SIZE + FRAME_ARENA_SIZE;
var app_memory: [APP_MEMORY_SIZE]u8 = undefined;
var app_arena: Arena = undefined;
var level_arena: Arena = undefined;
var frame_arena: Arena = undefined;

/// Core data
var playdate_api: *pd.PlaydateAPI = undefined;
var assets: renderer.Assets = undefined;
var level: level_loader.Level = undefined;
var flow_field: FlowField = undefined; //The enemies' path to the player, sized to the level
var game_state: state.GameState = .{};

/// The levels (generated by convert_tilemaps.py). Each survival run is on a random one, never the same twice in a row,
/// unless a level is forced (debug: `zig build -Dlevel=<name>`). A story chapter is always on its own level
const LEVEL_NAMES = level_descs.LEVEL_NAMES;
var current_level: ?usize = null;
var bests: [LEVEL_NAMES.len]save_data.SaveData = @splat(save_data.SaveData{}); //Per level: read once at init, a level's written when a run on it ends with a new best
comptime {
    for (LEVEL_NAMES) |n| if (n.len > save_data.MAX_LEVEL_NAME_LEN) @compileError("level name too long for its save file name: " ++ n);
}
const forced_level: ?usize = forcedLevelOption();
var level_rng: std.Random.DefaultPrng = undefined; //Seeded from the clock at init: picks levels only, never gameplay

/// The level `-Dlevel=<name>` names, checked at compile time
fn forcedLevelOption() ?usize {
    if (build_options.level.len == 0) return null;
    inline for (LEVEL_NAMES, 0..) |n, i| {
        if (comptime std.mem.eql(u8, n, build_options.level)) return i;
    }
    @compileError("-Dlevel must name one of the LEVEL_NAMES in level_descs.zig");
}

/// What is up. The simulation only ticks while `playing`; the world is drawn under `run_end` too. Changes happen at
/// a frame boundary
const ScreenUp = union(enum) {
    title: screens.Title,
    playing,
    run_end: state.RunEnd,
    story_card: screens.StoryCard,
};
var screen: ScreenUp = .{ .title = .{} };
var mode: screens.Mode = .survival; //Of the run being played (or last played)
var story_save: story.Save = .{}; //Read once at init, written at chapter boundaries
var chapter: u8 = 0; //Story: the chapter being played, or on its card
var chapter_secs: f32 = 0; //Story: play time of every attempt at this chapter so far (for judging its length)
var chapter_deaths: u16 = 0;
var story_finished: story.Save = .{}; //The totals of the story just finished, for The End card

/// Frame timing and requests from outside the frame loop
var time_last_tick_ms: u32 = 0;
var restart_requested = false;
var title_requested = false;
var invincible_menu_item: ?*pd.PDMenuItem = null; //Debug builds only

/// Debug logging
const debug_logging = builtin.mode == .debug;
var last_log_time_ms: u32 = 0;
var last_render_stats: renderer.RenderStats = .{ .drawn = 0 };
var sim_ms_max: f32 = 0; //Slowest game.tick since the last status line

/// Exposed via the shared library to the Playdate runner which forwards on events
///
pub export fn eventHandler(playdate: [*c]pd.PlaydateAPI, event: pd.PDSystemEvent, _: c_ulong) callconv(.c) c_int {
    switch (event) {
        pd.kEventInit => gameInit(playdate),
        //Don't count the time spent paused or in the menu as a frame
        pd.kEventResume, pd.kEventUnlock => resetFrameTimer(),
        else => {},
    }
    return 0;
}

/// Upfront setup - carves out the memory arenas and loads all assets
///
fn gameInit(playdate: [*c]pd.PlaydateAPI) void {
    playdate_api = playdate;
    const sys = playdate_api.system.*;
    if (debug_logging) {
        //Start each run with a fresh log file
        if (playdate_api.file.*.open.?("log.txt", pd.kFileWrite)) |h| _ = playdate_api.file.*.close.?(h);
    }

    app_arena = Arena.init("app", &app_memory);
    level_arena = app_arena.subArena("level", LEVEL_ARENA_SIZE);
    frame_arena = app_arena.subArena("frame", FRAME_ARENA_SIZE);

    sys.setUpdateCallback.?(gameUpdateWrapper, null);
    //The system menu has room for three of the game's own items
    if (sys.addMenuItem.?("Restart Level", restartLevel, null) == null) debugLog("WARNING: no room for the Restart Level menu item", .{});
    if (sys.addMenuItem.?("Title", goToTitle, null) == null) debugLog("WARNING: no room for the Title menu item", .{});
    if (builtin.mode == .debug) {
        //Debug only: `zig build -Dinvincible` (or `tools/sim.ps1 -Invincible`) starts with it ticked
        game_state.invincible = build_options.invincible;
        invincible_menu_item = sys.addCheckmarkMenuItem.?("Invincible", @intFromBool(game_state.invincible), toggleInvincible, null);
        if (invincible_menu_item == null) debugLog("WARNING: no room for the Invincible menu item", .{});
    }

    //Locked at TARGET_FPS; `zig build -Duncapped` runs flat out (0) so the FPS counter shows the headroom
    playdate_api.display.*.setRefreshRate.?(if (build_options.uncapped) 0 else @floatFromInt(consts.TARGET_FPS));

    level_rng = std.Random.DefaultPrng.init(@as(u64, sys.getSecondsSinceEpoch.?(null)) << 16 ^ sys.getCurrentTimeMilliseconds.?());
    if (debug_logging) sys.resetElapsedTime.?();
    assets = renderer.loadAssets(playdate_api, &LEVEL_NAMES);
    if (debug_logging) debugLog("load: assets {d:.1}ms", .{sys.getElapsedTime.?() * 1000});

    for (&bests, LEVEL_NAMES) |*b, name| b.* = readSave(name);
    story_save = readStorySave();
    resetFrameTimer();
    debugLog("init complete: story chapter {d}, L1 hot set budget {d} bytes (collision {d}, separation {d}, {d} per sprite drawn)", .{ story_save.chapter + 1, memory.HOT_SET_BUDGET, state.COLLISION_HOT_SET_BYTES, enemy_move_sys.SEPARATION_HOT_SET_BYTES, renderer.BYTES_PER_DRAW_ITEM });
}

/// Replace the current level, releasing everything the previous one allocated. The flow field starts out leading
/// to the level's start cell
///
fn loadLevel(index: usize) void {
    var name_buf: [64]u8 = undefined;
    const file_name = std.fmt.bufPrintSentinel(&name_buf, "{s}.bin", .{LEVEL_NAMES[index]}, 0) catch unreachable;
    if (debug_logging) playdate_api.system.*.resetElapsedTime.?();
    level_arena.reset();
    //The file's bytes are only needed while parsing, so they go in the frame arena
    const bytes = readFile(file_name, &frame_arena) orelse std.debug.panic("loadLevel: couldn't read {s}", .{file_name});
    level = level_loader.parse(bytes, &level_arena) catch |err| std.debug.panic("loadLevel {s}: {s}", .{ file_name, @errorName(err) });
    flow_field = FlowField.init(&level_arena, &level.collision_grid, level.collision_grid.cellIndex(level.start_pos));
    current_level = index;
    if (debug_logging) {
        debugLog("level {s}: {d} objects, {d} drop points, {d} spawn cells, level arena {d}/{d} bytes, flow field {d} bytes, bullet walls {d} bytes, loaded in {d:.2}ms", .{ LEVEL_NAMES[index], level.obj_world_positions.len, level.drop_cells.len, level.spawn_cells.all.len, level_arena.used(), level_arena.capacity(), flow_field.hotSetBytes(), level.collision_grid.cells.len, playdate_api.system.*.getElapsedTime.?() * 1000 });
        if (flow_field.hotSetBytes() > memory.HOT_SET_BUDGET) debugLog("WARNING: flow field ({d} bytes) is larger than the L1 hot set budget, enemy movement will miss the cache", .{flow_field.hotSetBytes()});
        if (level.collision_grid.cells.len > memory.HOT_SET_BUDGET) debugLog("WARNING: collision grid ({d} bytes) is larger than the L1 hot set budget, bullet wall tests will miss the cache", .{level.collision_grid.cells.len});
    }
}

/// Start a fresh survival run on the next level: a file read, once per run
///
fn startRun() void {
    const next = level_select.next(level_rng.random(), LEVEL_NAMES.len, current_level, forced_level);
    if (next != current_level) loadLevel(next);
    game.beginRun(&game_state, level.start_pos);
    mode = .survival;
    screen = .playing;
}

/// Start (or retry) story chapter `index` on its own level
///
fn startChapter(index: u8) void {
    const c = story.CHAPTERS[index];
    if (c.level != current_level) loadLevel(c.level);
    game.beginChapter(&game_state, level.start_pos, c);
    mode = .story;
    chapter = index;
    screen = .playing;
}

/// Go again after a death or from the menu: the same chapter in story, the next level in survival
///
fn restart() void {
    switch (mode) {
        .survival => startRun(),
        .story => startChapter(chapter),
    }
}

/// The chapter is complete: add its time and deaths to the story's, save the next chapter to play (a fresh story
/// after the last) and show its outro card
///
fn completeChapter() void {
    chapter_secs += game_state.run_time;
    const secs: u32 = @intFromFloat(chapter_secs);
    const last = chapter + 1 == story.CHAPTERS.len;
    const totals = story.Save{ .chapter = if (last) 0 else chapter + 1, .play_secs = story_save.play_secs +| secs, .deaths = story_save.deaths +| chapter_deaths };
    if (last) story_finished = totals;
    story_save = if (last) .{} else totals;
    writeStorySave(story_save);
    screen = .{ .story_card = .{ .kind = .outro, .chapter = chapter, .secs = secs, .deaths = chapter_deaths } };
    debugLog("chapter complete: chapter={d} attempt={d:.1}s chapter_time={d}s deaths={d} kills={d} story_time={d}s story_deaths={d}", .{ chapter + 1, game_state.run_time, secs, chapter_deaths, game_state.player.kills, totals.play_secs, totals.deaths });
}

/// A on a story card: the intro starts its chapter, an outro leads to the next chapter's intro (or the end), and the
/// end goes back to the title
///
fn continueFromCard(card: screens.StoryCard) void {
    switch (card.kind) {
        .intro => {
            chapter_secs = 0;
            chapter_deaths = 0;
            startChapter(card.chapter);
        },
        .outro => screen = .{ .story_card = if (card.chapter + 1 < story.CHAPTERS.len)
            .{ .kind = .intro, .chapter = card.chapter + 1 }
        else
            .{ .kind = .the_end, .chapter = card.chapter, .secs = story_finished.play_secs, .deaths = story_finished.deaths } },
        .the_end => screen = .{ .title = .{} },
    }
}

/// The player died: freeze on the run end screen, and save the score if it is a new best (the one file write
/// in the frame loop, once per run)
///
fn endRun() void {
    const p = game_state.player;
    const lvl = current_level.?;
    //A story chapter is retried, not scored against the level's best
    const new_best = mode == .survival and game.isNewBest(&game_state, bests[lvl].best_score);
    screen = .{ .run_end = .{ .new_best = new_best } };
    if (mode == .story) {
        chapter_secs += game_state.run_time;
        chapter_deaths +|= 1;
    }
    if (new_best) {
        bests[lvl].best_score = p.score;
        writeSave(LEVEL_NAMES[lvl], bests[lvl]);
    }
    debugLog("run over: mode={s} level={s} wave={d} score={d} best={d} new_best={} time={d:.1}s kills={d} best_streak={d}", .{ @tagName(mode), LEVEL_NAMES[lvl], game_state.spawner.wave, p.score, bests[lvl].best_score, new_best, game_state.run_time, p.kills, p.best_streak });
}

/// The whole of a file in the game's folder, read into `arena`, or null if it can't be read
///
fn readFile(name: [*:0]const u8, arena: *Arena) ?[]const u8 {
    const file = playdate_api.file.*;
    var stat: pd.FileStat = undefined;
    if (file.stat.?(name, &stat) != 0) return null;
    const handle = file.open.?(name, pd.kFileRead) orelse return null;
    defer _ = file.close.?(handle);

    const bytes = arena.alloc(u8, stat.size);
    var read_len: usize = 0;
    while (read_len < bytes.len) {
        const n = file.read.?(handle, bytes[read_len..].ptr, @intCast(bytes.len - read_len));
        if (n <= 0) return null;
        read_len += @intCast(n);
    }
    return bytes;
}

/// The level's saved best, or a fresh save if there is none yet (or it can't be read)
///
fn readSave(level_name: []const u8) save_data.SaveData {
    const file = playdate_api.file.*;
    var name_buf: [save_data.FILE_NAME_CAPACITY]u8 = undefined;
    const handle = file.open.?(save_data.fileName(&name_buf, level_name), pd.kFileReadData) orelse return .{};
    defer _ = file.close.?(handle);
    var bytes: [save_data.SIZE]u8 = undefined;
    const n = file.read.?(handle, &bytes, bytes.len);
    if (n != bytes.len) return .{};
    return save_data.decode(&bytes);
}

/// The story save, or a fresh story if there is none yet (or it can't be read)
///
fn readStorySave() story.Save {
    const file = playdate_api.file.*;
    const handle = file.open.?(story.FILE_NAME, pd.kFileReadData) orelse return .{};
    defer _ = file.close.?(handle);
    var bytes: [story.SAVE_SIZE]u8 = undefined;
    const n = file.read.?(handle, &bytes, bytes.len);
    if (n != bytes.len) return .{};
    return story.decode(&bytes);
}

fn writeStorySave(save: story.Save) void {
    const file = playdate_api.file.*;
    const handle = file.open.?(story.FILE_NAME, pd.kFileWrite) orelse {
        debugLog("WARNING: couldn't open {s} to save the story", .{story.FILE_NAME});
        return;
    };
    defer _ = file.close.?(handle);
    const bytes = story.encode(save);
    if (file.write.?(handle, &bytes, bytes.len) != bytes.len) debugLog("WARNING: couldn't write {s}", .{story.FILE_NAME});
}

fn writeSave(level_name: []const u8, data: save_data.SaveData) void {
    const file = playdate_api.file.*;
    var name_buf: [save_data.FILE_NAME_CAPACITY]u8 = undefined;
    const file_name = save_data.fileName(&name_buf, level_name);
    const handle = file.open.?(file_name, pd.kFileWrite) orelse {
        debugLog("WARNING: couldn't open {s} to save the best score", .{file_name});
        return;
    };
    defer _ = file.close.?(handle);
    const bytes = save_data.encode(data);
    if (file.write.?(handle, &bytes, bytes.len) != bytes.len) debugLog("WARNING: couldn't write {s}", .{file_name});
}

/// Called from the system menu by the user if they want to restart. Handled at the start of the next frame
///
fn restartLevel(_: ?*anyopaque) callconv(.c) void {
    restart_requested = true;
}

/// Called from the system menu: back to the title screen at the start of the next frame
///
fn goToTitle(_: ?*anyopaque) callconv(.c) void {
    title_requested = true;
}

/// Debug system menu checkmark: read back its state, so enemies stop (or start) hurting the player
///
fn toggleInvincible(_: ?*anyopaque) callconv(.c) void {
    game_state.invincible = playdate_api.system.*.getMenuItemValue.?(invincible_menu_item) != 0;
}

fn resetFrameTimer() void {
    time_last_tick_ms = playdate_api.system.*.getCurrentTimeMilliseconds.?();
}

/// Ticks the main game update and render once per frame
///
fn gameUpdateWrapper(_: ?*anyopaque) callconv(.c) c_int {
    const sys = playdate_api.system.*;
    frame_arena.reset();

    if (title_requested) {
        title_requested = false;
        restart_requested = false;
        screen = .{ .title = .{} };
    }
    if (restart_requested) {
        restart_requested = false;
        //Only a run (or its end screen) has a level to restart
        if (screen == .playing and mode == .story) chapter_secs += game_state.run_time; //An abandoned attempt still counts
        if (screen == .playing or screen == .run_end) restart();
    }

    const now_ms = sys.getCurrentTimeMilliseconds.?();
    const dt = @min(@as(f32, @floatFromInt(now_ms -% time_last_tick_ms)) * 0.001, consts.MAX_FRAME_DT);
    time_last_tick_ms = now_ms;

    const input = readInput();
    switch (screen) {
        .title => |*title| if (title.update(input)) |choice| switch (choice) {
            .survival => startRun(),
            .story => screen = .{ .story_card = .{ .kind = .intro, .chapter = story_save.chapter } },
        },
        .story_card => |*card| if (card.update(input, dt)) continueFromCard(card.*),
        .run_end => |*over| if (over.update(input, dt)) restart(),
        .playing => {
            if (debug_logging) sys.resetElapsedTime.?();
            const result = game.tick(&game_state, &level, &flow_field, input, dt, &frame_arena);
            if (debug_logging) sim_ms_max = @max(sim_ms_max, sys.getElapsedTime.?() * 1000);
            switch (result) {
                .playing => {},
                .player_died => endRun(),
                .chapter_complete => completeChapter(),
            }
        },
    }

    switch (screen) {
        .title => |title| renderer.renderTitle(playdate_api, &assets, title),
        .story_card => |card| renderer.renderStoryCard(playdate_api, &assets, card),
        .playing, .run_end => {
            const hud = renderer.Hud{
                .best_score = bests[current_level.?].best_score,
                .level_name = LEVEL_NAMES[current_level.?],
                .game_over = if (screen == .run_end) screen.run_end else null,
                .chapter = if (mode == .story) chapter else null,
            };
            last_render_stats = renderer.render(playdate_api, &assets, &game_state, &level, current_level.?, hud, &frame_arena);
        },
    }

    logStatus(now_ms);
    return 1; //Inform the SDK we have stuff to render
}

/// Snapshot this frame's buttons and crank
///
fn readInput() state.Input {
    const sys = playdate_api.system.*;
    var current: pd.PDButtons = undefined;
    var pushed: pd.PDButtons = undefined;
    var released: pd.PDButtons = undefined;
    sys.getButtonState.?(&current, &pushed, &released);

    return .{
        .left = (current & pd.kButtonLeft) != 0,
        .right = (current & pd.kButtonRight) != 0,
        .up = (current & pd.kButtonUp) != 0,
        .down = (current & pd.kButtonDown) != 0,
        .fire_held = (current & (pd.kButtonA | pd.kButtonB)) != 0,
        .fire_pressed = (pushed & (pd.kButtonA | pd.kButtonB)) != 0,
        .up_pressed = (pushed & pd.kButtonUp) != 0,
        .down_pressed = (pushed & pd.kButtonDown) != 0,
        .crank_delta = sys.getCrankChange.?(),
    };
}

/// Once a second write a status line so a run can be inspected from the logs
///
fn logStatus(now_ms: u32) void {
    if (!debug_logging or now_ms -% last_log_time_ms < 1000) return;
    last_log_time_ms = now_ms;
    if (screen != .playing and screen != .run_end) {
        debugLog("t={d}ms screen={s} story_chapter={d}", .{ now_ms, @tagName(screen), story_save.chapter + 1 });
        return;
    }

    const p = game_state.player;
    //The nearest drop, so a scripted run can walk to it
    const drops = &game_state.drops;
    var near: usize = 0;
    for (drops.positions(), 0..) |d, i| {
        if (maths.magnitudeSqrd(d - p.pos) < maths.magnitudeSqrd(drops.pos[near] - p.pos)) near = i;
    }
    const near_pos = if (drops.len > 0) drops.pos[near] else p.pos;
    //Enemies in view: what the player actually sees of a wave
    var on_screen: u32 = 0;
    for (game_state.enemies.positions()) |e| {
        const d = e - game_state.camera.pos;
        if (@abs(d[0]) < consts.VIEW_HALF_WIDTH and @abs(d[1]) < consts.VIEW_HALF_HEIGHT) on_screen += 1;
    }
    debugLog("t={d}ms screen={s} mode={s} chapter={d} level={s} wave={d}:{s} enemies={d} on_screen={d} health={d} score={d} combo={d} pos=({d:.2},{d:.2}) bullets={d} drops={d} invincible={} near={s}({d:.2},{d:.2}) aim=({d:.2},{d:.2}) target={s} crank={d:.1} frame_mem={d} drawn={d} gibs={d} droplets={d} splats={d} sim_ms_max={d:.2}", .{ now_ms, @tagName(screen), @tagName(mode), if (mode == .story) chapter + 1 else 0, LEVEL_NAMES[current_level.?], game_state.spawner.wave, @tagName(game_state.spawner.phase), game_state.enemies.len, on_screen, p.health, p.score, p.kill_streak, p.pos[0], p.pos[1], game_state.bullets.ammo, drops.len, game_state.invincible, if (drops.len > 0) @tagName(drops.kind[near]) else "none", near_pos[0], near_pos[1], p.facing_dir[0], p.facing_dir[1], if (p.target_pos != null) "yes" else "no", playdate_api.system.*.getCrankAngle.?(), frame_arena.high_water, last_render_stats.drawn, game_state.gore.gibs.liveCount(), game_state.gore.droplets.liveCount(), game_state.gore.pools.liveCount() + game_state.gore.spatters.liveCount(), sim_ms_max });
    sim_ms_max = 0;
}

/// Debug builds only: write to the Playdate console and append to `log.txt` in the game's data folder.
/// In the simulator that is `<PlaydateSDK>/Disk/Data/<bundleID>/log.txt`
///
fn debugLog(comptime fmt: []const u8, args: anytype) void {
    if (!debug_logging) return;

    var buf: [384]u8 = undefined;
    const msg = std.mem.printSentinel(&buf, "until-none: " ++ fmt, args, 0) catch return;
    playdate_api.system.*.logToConsole.?("%s", msg.ptr);

    const file = playdate_api.file.*;
    const handle = file.open.?("log.txt", pd.kFileAppend) orelse return;
    defer _ = file.close.?(handle);
    _ = file.write.?(handle, msg.ptr, @intCast(msg.len));
    _ = file.write.?(handle, "\n", 1);
}
